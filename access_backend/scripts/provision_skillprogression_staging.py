"""
Create PostgreSQL role + database for isolated skill progression staging (Phase 1).

Uses admin credentials from access_backend/.env only to CREATE ROLE/DATABASE.
Does not modify data in the shared postgres development database.

Usage:
  cd access_backend
  python scripts/provision_skillprogression_staging.py
"""

from __future__ import annotations

import secrets
import sys
from pathlib import Path
from urllib.parse import quote_plus

import psycopg
from dotenv import load_dotenv

BACKEND = Path(__file__).resolve().parents[1]
load_dotenv(BACKEND / ".env")

STAGING_DB = "access_skillprogression_staging"
STAGING_ROLE = "access_skillprogression_app"
ENV_FILE = BACKEND / ".env.skillprogression_staging"
UPLOAD_DIR = "uploads_staging_skillprogression"
API_PORT = 3011

PROTECTED_DATABASES = ("postgres", "access_uat", "access_waverep_test")


def _admin_conninfo(dbname: str = "postgres") -> str:
    from app.config import settings

    user = quote_plus(settings.db_username)
    password = quote_plus(settings.db_password)
    host = settings.db_host
    port = settings.db_port
    return f"postgresql://{user}:{password}@{host}:{port}/{dbname}"


def _assert_shared_dev_name() -> None:
    from app.config import settings

    if settings.db_name != "postgres":
        print(
            f"STOP: expected shared dev DB_NAME=postgres, got {settings.db_name!r}. "
            "Refusing to provision from this .env."
        )
        sys.exit(1)


def _write_env_file(password: str) -> None:
    content = f"""# Generated by scripts/provision_skillprogression_staging.py — do not commit.
# Load:  $env:ACCESS_ENV_FILE = (Resolve-Path .env.skillprogression_staging).Path

DB_HOST=localhost
DB_PORT=5432
DB_USERNAME={STAGING_ROLE}
DB_PASSWORD={password}
DB_NAME={STAGING_DB}

DATABASE_URL=postgresql+psycopg://{STAGING_ROLE}:{password}@localhost:5432/{STAGING_DB}

SKILL_PROGRESSION_ACTIVE_POLICY=v1

API_HOST=0.0.0.0
API_PORT={API_PORT}
API_PUBLIC_HOST=127.0.0.1
ALLOWED_HOSTS=127.0.0.1,127.0.0.1:{API_PORT},localhost,localhost:{API_PORT}
CORS_ORIGINS=http://127.0.0.1:{API_PORT},http://localhost:{API_PORT}

UPLOAD_DIR={UPLOAD_DIR}
JWT_SECRET=staging_skillprogression_{secrets.token_hex(16)}

RECREATE_DB=false
"""
    ENV_FILE.write_text(content, encoding="utf-8")
    print(f"Wrote {ENV_FILE.name} (local only, gitignored).")


def main() -> int:
    _assert_shared_dev_name()
    password = secrets.token_urlsafe(24)

    admin = _admin_conninfo("postgres")
    print(f"Provisioning role={STAGING_ROLE} database={STAGING_DB} on localhost...")

    role_existed = False
    with psycopg.connect(admin, autocommit=True) as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (STAGING_ROLE,))
            role_existed = cur.fetchone() is not None
            if role_existed:
                safe_pw = password.replace("'", "''")
                cur.execute(
                    f"ALTER ROLE {STAGING_ROLE} WITH LOGIN PASSWORD '{safe_pw}'"
                )
                print(f"Role {STAGING_ROLE} exists; password synced for new env file.")
            else:
                safe_pw = password.replace("'", "''")
                cur.execute(
                    f"CREATE ROLE {STAGING_ROLE} WITH LOGIN PASSWORD '{safe_pw}' "
                    "NOSUPERUSER NOCREATEDB NOCREATEROLE"
                )
                print(f"Created role {STAGING_ROLE}.")

            cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (STAGING_DB,))
            if cur.fetchone():
                print(f"Database {STAGING_DB} already exists.")
            else:
                cur.execute(f'CREATE DATABASE "{STAGING_DB}" OWNER {STAGING_ROLE}')
                print(f"Created database {STAGING_DB}.")

            for dbname in PROTECTED_DATABASES:
                cur.execute(f"REVOKE ALL ON DATABASE {dbname} FROM {STAGING_ROLE}")
            cur.execute(f"GRANT CONNECT ON DATABASE {STAGING_DB} TO {STAGING_ROLE}")
            cur.execute(f"REVOKE CONNECT ON DATABASE {STAGING_DB} FROM PUBLIC")

    staging_admin = _admin_conninfo(STAGING_DB)
    with psycopg.connect(staging_admin, autocommit=True) as conn:
        with conn.cursor() as cur:
            cur.execute(f"GRANT ALL ON SCHEMA public TO {STAGING_ROLE}")
            cur.execute(f"ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO {STAGING_ROLE}")
            cur.execute(
                f"ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO {STAGING_ROLE}"
            )

    _write_env_file(password)

    upload_path = BACKEND / UPLOAD_DIR
    upload_path.mkdir(exist_ok=True)
    print(f"Upload directory ready: {upload_path.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
