            padding: const EdgeInsets.all(18),
            decoration: evalCardDecoration(borderColor: levelColor.withValues(alpha: 0.22)),
            child: Column(
              children: [
                Text(
                  '${result.overallPercent} / 100',
                  style: dashText(const TextStyle(
                    fontSize: 40,
                    fontWeight: FontWeight.w900,
                    letterSpacing: -1,
