const _modelFooter =
    'This evaluation was generated using the EfficientNet-B0 media quality model. '
    'Human-friendly feedback is generated by Google Gemini AI.';

class EvaluationDetailedAnalysisScreen extends StatefulWidget {
  const EvaluationDetailedAnalysisScreen({
    super.key,
    required this.result,
    this.geminiFeedback,
    this.title,
    this.comparisonEvaluations = const [],
    this.initialTab = 0,
  });

  final PhotoEvaluationResult result;
  final MediaEvaluationFeedback? geminiFeedback;
  final String? title;
  final List<PhotoEvaluationResult> comparisonEvaluations;
  final int initialTab;

  @override
  State<EvaluationDetailedAnalysisScreen> createState() => _EvaluationDetailedAnalysisScreenState();
}

class _EvaluationDetailedAnalysisScreenState extends State<EvaluationDetailedAnalysisScreen>
    with SingleTickerProviderStateMixin {
  late final TabController _tabs;

  @override
  void initState() {
    super.initState();
    _tabs = TabController(length: 3, vsync: this, initialIndex: widget.initialTab.clamp(0, 2));
  }

  @override
  void dispose() {
    _tabs.dispose();
    super.dispose();
  }

  MediaEvaluationFeedback get _feedback =>
      widget.geminiFeedback ?? widget.result.geminiFeedback ?? MediaEvaluationFeedback.fromLocal(widget.result);

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: kEvalBg,
      appBar: AppBar(
        backgroundColor: kEvalBg,
        foregroundColor: kDashTextPrimary,
        elevation: 0,
        scrolledUnderElevation: 0,
        title: Text(
          'Detailed Analysis',
          style: dashText(const TextStyle(fontWeight: FontWeight.w800, fontSize: 18)),
        ),
        bottom: TabBar(
          controller: _tabs,
          labelColor: kEvalSecondary,
          unselectedLabelColor: kDashTextSecondary,
          indicatorColor: kEvalSecondary,
          indicatorWeight: 3,
          labelStyle: dashText(const TextStyle(fontWeight: FontWeight.w700, fontSize: 13)),
          unselectedLabelStyle: dashText(const TextStyle(fontWeight: FontWeight.w600, fontSize: 13)),
          tabs: const [
            Tab(text: 'Summary'),
            Tab(text: 'Technical'),
            Tab(text: 'Comparison'),
          ],
        ),
      ),
      body: TabBarView(
        controller: _tabs,
        children: [
          _SummaryTab(result: widget.result, feedback: _feedback, title: widget.title),
          _TechnicalTab(result: widget.result),
          _ComparisonTab(
            result: widget.result,
            others: widget.comparisonEvaluations,
          ),
        ],
      ),
    );
  }
}

