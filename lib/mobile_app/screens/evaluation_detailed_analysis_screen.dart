          const SizedBox(width: 8),
          Expanded(
            child: Text(
              _modelFooter,
              style: evalBodyStyle.copyWith(fontSize: 11, height: 1.45),
            ),
          ),
        ],
      ),
    );
  }
}

void openEvaluationDetailedAnalysis(
  BuildContext context, {
  required PhotoEvaluationResult result,
  MediaEvaluationFeedback? geminiFeedback,
  String? title,
  List<PhotoEvaluationResult> comparisonEvaluations = const [],
  int initialTab = 0,
}) {
  Navigator.of(context).push(
    MaterialPageRoute<void>(
      builder: (_) => EvaluationDetailedAnalysisScreen(
        result: result,
        geminiFeedback: geminiFeedback,
        title: title,
        comparisonEvaluations: comparisonEvaluations,
        initialTab: initialTab,
      ),
    ),
  );
}
