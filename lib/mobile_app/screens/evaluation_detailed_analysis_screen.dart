class _TechnicalCriterionTile extends StatefulWidget {
  const _TechnicalCriterionTile({required this.criterion});

  final CriterionScore criterion;

  @override
  State<_TechnicalCriterionTile> createState() => _TechnicalCriterionTileState();
}

class _TechnicalCriterionTileState extends State<_TechnicalCriterionTile> with SingleTickerProviderStateMixin {
  late final AnimationController _controller;
  late final Animation<double> _progress;

  @override
  void initState() {
    super.initState();
    _controller = AnimationController(vsync: this, duration: const Duration(milliseconds: 850));
    _progress = CurvedAnimation(parent: _controller, curve: Curves.easeOutCubic);
    _controller.forward();
  }

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final meta = criterionMetaFor(widget.criterion);
    final percent = widget.criterion.percentScore;
    final color = criterionPercentColor(percent);
    final explanation = widget.criterion.explanation.trim().isNotEmpty
        ? widget.criterion.explanation
        : widget.criterion.label;

    return Container(
      margin: const EdgeInsets.only(bottom: 12),
      padding: const EdgeInsets.all(14),
      decoration: evalCardDecoration(),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Container(
                width: 40,
                height: 40,
                decoration: BoxDecoration(
                  color: color.withValues(alpha: 0.12),
                  borderRadius: BorderRadius.circular(12),
                ),
                child: Icon(meta.icon, color: color, size: 20),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(widget.criterion.name, style: evalCardTitleStyle.copyWith(fontSize: 14)),
                    const SizedBox(height: 3),
                    Text(meta.description, style: evalBodyStyle.copyWith(fontSize: 11, height: 1.35)),
                  ],
                ),
              ),
              Text(
                '$percent',
                style: TextStyle(color: color, fontSize: 16, fontWeight: FontWeight.w900),
              ),
            ],
          ),
          const SizedBox(height: 10),
          AnimatedBuilder(
            animation: _progress,
            builder: (_, __) {
              return ClipRRect(
                borderRadius: BorderRadius.circular(5),
                child: Stack(
                  children: [
                    Container(height: 6, color: kDashBorder),
                    FractionallySizedBox(
                      widthFactor: (percent / 100) * _progress.value,
                      child: Container(
                        height: 6,
                        decoration: BoxDecoration(
                          gradient: LinearGradient(colors: [color.withValues(alpha: 0.8), color]),
                        ),
                      ),
                    ),
                  ],
                ),
              );
            },
          ),
          const SizedBox(height: 8),
          Text(explanation, style: evalBodyStyle.copyWith(fontSize: 11, height: 1.4)),
        ],
      ),
    );
  }
}

class _ComparisonTab extends StatelessWidget {
  const _ComparisonTab({
    required this.result,
    required this.others,
  });

  final PhotoEvaluationResult result;
  final List<PhotoEvaluationResult> others;

  @override
  Widget build(BuildContext context) {
    final criteria = result.displayCriteria(isVideo: result.isVideo);
    final hasOthers = others.isNotEmpty;

    return ListView(
      padding: mobileScrollPadding(context, top: 16, bottom: 28),
      children: [
        Text(
          hasOthers
              ? 'How this submission compares to your recent evaluations'
              : 'Complete more evaluations to unlock comparison insights.',
          style: evalBodyStyle.copyWith(fontSize: 13),
        ),
        const SizedBox(height: 14),
        if (!hasOthers)
          MemberDashboardEmptyState(
            icon: Icons.compare_arrows_rounded,
            message: 'No comparison data yet.\nSave a few evaluations to see trends.',
            iconColor: kEvalSecondary,
          )
        else ...[
          _OverallComparisonCard(current: result, others: others),
          const SizedBox(height: 14),
          ...criteria.map((c) {
            final avg = _averageCriterionPercent(others, c.name);
            final delta = c.percentScore - avg;
            return _ComparisonCriterionRow(
              name: c.name,
              current: c.percentScore,
              average: avg.round(),
              delta: delta,
            );
          }),
        ],
        const SizedBox(height: 20),
        const _ModelFooter(),
      ],
    );
  }

  double _averageCriterionPercent(List<PhotoEvaluationResult> list, String name) {
    final values = <int>[];
    for (final ev in list) {
      for (final c in ev.criteria) {
        if (c.name == name) values.add(c.percentScore);
      }
    }
    if (values.isEmpty) return 0;
    return values.reduce((a, b) => a + b) / values.length;
  }
}

class _OverallComparisonCard extends StatelessWidget {
  const _OverallComparisonCard({required this.current, required this.others});

  final PhotoEvaluationResult current;
  final List<PhotoEvaluationResult> others;

  @override
  Widget build(BuildContext context) {
    final avg = others.map((e) => e.overallPercent).reduce((a, b) => a + b) / others.length;
    final delta = current.overallPercent - avg;
    final deltaLabel = delta >= 0 ? '+${delta.round()} vs avg' : '${delta.round()} vs avg';
    final deltaColor = delta >= 0 ? kGreen : kOrange;

    return Container(
      padding: const EdgeInsets.all(16),
      decoration: evalCardDecoration(borderColor: kEvalSecondary.withValues(alpha: 0.2)),
      child: Row(
        children: [
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text('Your score', style: evalBodyStyle.copyWith(fontSize: 11)),
                Text(
                  '${current.overallPercent}',
                  style: dashText(const TextStyle(fontSize: 28, fontWeight: FontWeight.w900)),
                ),
              ],
            ),
          ),
          Icon(Icons.compare_arrows_rounded, color: kDashTextSecondary.withValues(alpha: 0.6)),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.end,
              children: [
                Text('Your average', style: evalBodyStyle.copyWith(fontSize: 11)),
                Text(
                  avg.round().toString(),
                  style: dashText(const TextStyle(fontSize: 28, fontWeight: FontWeight.w900)),
                ),
              ],
            ),
          ),
          const SizedBox(width: 12),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
            decoration: BoxDecoration(
              color: deltaColor.withValues(alpha: 0.12),
              borderRadius: BorderRadius.circular(10),
            ),
            child: Text(
              deltaLabel,
              style: TextStyle(color: deltaColor, fontWeight: FontWeight.w800, fontSize: 12),
            ),
          ),
        ],
      ),
    );
  }
}

class _ComparisonCriterionRow extends StatelessWidget {
  const _ComparisonCriterionRow({
    required this.name,
    required this.current,
    required this.average,
    required this.delta,
  });

  final String name;
  final int current;
  final int average;
  final double delta;

  @override
  Widget build(BuildContext context) {
    final meta = kCriterionMeta[name];
    final deltaColor = delta >= 0 ? kGreen : kOrange;
    final deltaText = delta >= 0 ? '+${delta.round()}' : delta.round().toString();

    return Container(
      margin: const EdgeInsets.only(bottom: 10),
      padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 12),
      decoration: evalCardDecoration(),
      child: Row(
        children: [
          if (meta != null)
            Icon(meta.icon, size: 18, color: kEvalSecondary)
          else
            const Icon(Icons.analytics_outlined, size: 18, color: kEvalSecondary),
          const SizedBox(width: 10),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(name, style: evalCardTitleStyle.copyWith(fontSize: 13)),
                Text('Avg $average · You $current', style: evalBodyStyle.copyWith(fontSize: 11)),
              ],
            ),
          ),
          Text(
            deltaText,
            style: TextStyle(color: deltaColor, fontWeight: FontWeight.w800, fontSize: 13),
          ),
        ],
      ),
    );
  }
}

class _ModelFooter extends StatelessWidget {
  const _ModelFooter();

  @override
  Widget build(BuildContext context) {
