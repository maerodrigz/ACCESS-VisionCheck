#!/usr/bin/env python3
"""Phase 4A machine-only evaluation on the frozen independent holdout.

Produces hybrid measurements, experimental feedback, optional live MUSIQ, and
EfficientNet baseline scores. Never writes production DB rows. Never substitutes
historical MUSIQ CSV scores for holdout images. Does not invent human ratings.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

_TOOLKIT = Path(__file__).resolve().parent
_REPO = _TOOLKIT.parents[1]
_BACKEND = _REPO / "access_backend"
for path in (_BACKEND, str(_TOOLKIT), str(_REPO)):
    p = str(path)
    if p not in sys.path:
        sys.path.insert(0, p)

DEFAULT_MANIFEST = _TOOLKIT / "workspace" / "phase4a_indval" / "holdout_manifest.csv"
DEFAULT_OUT = _TOOLKIT / "workspace" / "phase4a_indval" / "machine_output"
FREEZE = _TOOLKIT / "phase4a_freeze_manifest.json"


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))


def _write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    keys: list[str] = []
    for row in rows:
        for k in row:
            if k not in keys:
                keys.append(k)
    with path.open("w", newline="", encoding="utf-8") as handle:
        w = csv.DictWriter(handle, fieldnames=keys)
        w.writeheader()
        for row in rows:
            w.writerow({k: row.get(k, "") for k in keys})


def _score_hybrid(content: bytes) -> dict[str, Any]:
    from app.services.quality_shadow.classical import (
        classical_quality_from_bgr,
        color_criteria_from_bgr,
        decode_bgr_from_bytes,
    )
    from app.services.quality_shadow.feedback_generator import generate_hybrid_feedback
    from app.services.quality_shadow.musiq_opq import score_image_bytes_musiq

    bgr = decode_bgr_from_bytes(content)
    if bgr is None:
        return {"status": "error", "error": "decode_failed"}
    classical = classical_quality_from_bgr(bgr)
    color = color_criteria_from_bgr(bgr)
    musiq = score_image_bytes_musiq(content)
    feedback = generate_hybrid_feedback(
        criteria_q=classical.get("q"),
        criteria_raw=classical.get("raw"),
        color=color,
        musiq_opq_raw=musiq.get("musiq_opq_raw"),
        musiq_status=musiq.get("status"),
    )
    return {
        "status": "ok" if musiq.get("status") == "ok" else "partial",
        "criteria_q": classical.get("q"),
        "criteria_raw": classical.get("raw"),
        "criteria_badge_equal_bin": classical.get("badge_equal_bin"),
        "color": color,
        "classical_map_version": classical.get("map_version"),
        "musiq": musiq,
        "experimental_feedback": feedback,
    }


def _score_enet(content: bytes, file_name: str) -> dict[str, Any]:
    from tools.quality_validation.real_world_evaluate import evaluate_production_quality

    return evaluate_production_quality(content, file_name=file_name)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    ap.add_argument("--output", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--skip-enet", action="store_true")
    ap.add_argument("--skip-musiq", action="store_true", help="Force musiq unavailable without calling TF")
    args = ap.parse_args()

    if not args.manifest.is_file():
        raise SystemExit(
            f"Missing holdout manifest: {args.manifest}. Run select_phase4a_holdout.py first."
        )

    freeze = json.loads(FREEZE.read_text(encoding="utf-8")) if FREEZE.is_file() else {}
    rows = _read_csv(args.manifest)
    if args.limit is not None:
        rows = rows[: args.limit]

    args.output.mkdir(parents=True, exist_ok=True)
    per_image: list[dict[str, Any]] = []
    feedback_rows: list[dict[str, Any]] = []
    meta = {
        "started_at_utc": datetime.now(timezone.utc).isoformat(),
        "freeze_id": freeze.get("freeze_id"),
        "manifest": str(args.manifest),
        "n_target": len(rows),
        "cached_musiq_csv_used": False,
        "note": "Human ratings are not generated by this script.",
    }

    for row in rows:
        indval = row["indval_id"]
        path = Path(row["path"])
        print(f"[PHASE4A] {indval} {path.name}", flush=True)
        t0 = time.perf_counter()
        rec: dict[str, Any] = {
            "indval_id": indval,
            "source_media_key": row.get("source_media_key"),
            "pool": row.get("pool"),
            "file_sha256": row.get("file_sha256"),
            "path": str(path),
        }
        if not path.is_file():
            rec["status"] = "missing_file"
            rec["error"] = "image_not_found"
            per_image.append(rec)
            continue
        content = path.read_bytes()

        try:
            if args.skip_musiq:
                from unittest.mock import patch

                with patch(
                    "app.services.quality_shadow.musiq_opq.score_image_bytes_musiq",
                    return_value={
                        "status": "unavailable",
                        "musiq_opq_raw": None,
                        "musiq_scale": "approx_0_100_mos_like",
                        "model_id": "tfhub:google/musiq/paq2piq/1",
                        "engine_handle": None,
                        "error": "skipped_by_flag",
                    },
                ):
                    hybrid = _score_hybrid(content)
            else:
                hybrid = _score_hybrid(content)
            rec["hybrid_status"] = hybrid.get("status")
            q = hybrid.get("criteria_q") or {}
            badge = hybrid.get("criteria_badge_equal_bin") or {}
            for k, v in q.items():
                rec[f"hybrid_q_{k}"] = v
            for k, v in badge.items():
                rec[f"hybrid_badge_{k}"] = v
            musiq = hybrid.get("musiq") or {}
            rec["musiq_status"] = musiq.get("status")
            rec["musiq_opq_raw"] = musiq.get("musiq_opq_raw")
            rec["musiq_error"] = musiq.get("error")
            rec["musiq_engine_handle"] = musiq.get("engine_handle")
            fb = hybrid.get("experimental_feedback") or {}
            rec["feedback_ruleset_version"] = fb.get("feedback_ruleset_version")
            rec["experimental_issue_count"] = fb.get("issue_count")
            rec["experimental_summary"] = fb.get("experimental_summary")
            for obs in fb.get("observations") or []:
                feedback_rows.append(
                    {
                        "indval_id": indval,
                        "source_media_key": row.get("source_media_key"),
                        "criterion": obs.get("criterion"),
                        "rule_id": obs.get("rule_id"),
                        "observation_kind": obs.get("observation_kind"),
                        "severity": obs.get("severity"),
                        "suppressed": obs.get("suppressed"),
                        "observation": obs.get("observation"),
                        "suggested_improvement": obs.get("suggested_improvement"),
                        "q_value": obs.get("q_value"),
                        "raw_measurement": obs.get("raw_measurement"),
                        "confidence": obs.get("confidence"),
                    }
                )
            # Persist full hybrid JSON beside CSV for audit
            (args.output / "per_image_json").mkdir(exist_ok=True)
            (args.output / "per_image_json" / f"{indval}.json").write_text(
                json.dumps(hybrid, indent=2, default=str), encoding="utf-8"
            )
        except Exception as exc:  # noqa: BLE001
            rec["hybrid_status"] = "error"
            rec["error"] = f"hybrid: {exc}"

        if not args.skip_enet:
            try:
                enet = _score_enet(content, file_name=path.name)
                rec["enet_status"] = enet.get("analysis_status") or enet.get("status")
                rec["enet_error_code"] = enet.get("error_code")
                rec["enet_error_detail"] = enet.get("error_detail")
                rec["enet_overall_score"] = enet.get("overall_score")
                rec["enet_quality_engine"] = enet.get("quality_engine")
                rec["enet_opencv_fallback"] = enet.get("opencv_fallback")
                by_name = enet.get("criterion_scores") if isinstance(enet.get("criterion_scores"), dict) else {}
                for name in (
                    "Sharpness",
                    "Blur",
                    "Brightness",
                    "Contrast",
                    "Blocking Artifacts",
                    "Color Balance",
                    "Color Saturation",
                ):
                    slug = name.lower().replace(" ", "_")
                    rec[f"enet_{slug}"] = by_name.get(name)
            except Exception as exc:  # noqa: BLE001
                rec["enet_status"] = "error"
                rec["enet_error"] = str(exc)

        rec["elapsed_ms"] = round((time.perf_counter() - t0) * 1000.0, 3)
        per_image.append(rec)

    _write_csv(args.output / "machine_scores.csv", per_image)
    _write_csv(args.output / "experimental_feedback_observations.csv", feedback_rows)
    meta["finished_at_utc"] = datetime.now(timezone.utc).isoformat()
    meta["n_scored"] = len(per_image)
    meta["n_musiq_ok"] = sum(1 for r in per_image if r.get("musiq_status") == "ok")
    meta["n_musiq_unavailable"] = sum(
        1 for r in per_image if r.get("musiq_status") == "unavailable"
    )
    (args.output / "run_meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"[PHASE4A] machine scores -> {args.output}", flush=True)
    print(
        f"[PHASE4A] musiq_ok={meta['n_musiq_ok']} unavailable={meta['n_musiq_unavailable']}",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
